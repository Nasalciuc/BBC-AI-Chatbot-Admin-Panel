"""ci/schema_dictionary.py (PR-14) — the data dictionary, generated.

Writes docs/schema/DICTIONARY.md from a database: every public table, its
columns (type, null, default), whether RLS is on, and its indexes. Hand-kept
dictionaries drift (the March one lists 9 tables; there are far more).

  From the migrations:  run after ci/replay_migrations.sh (what CI builds).
  From production:      point PG* at a restore of `supabase db dump`, and
                        pass --source "live dump of <date>".

Usage: PG…=… python ci/schema_dictionary.py [--source TEXT] [--out PATH]
"""

from __future__ import annotations

import argparse
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def q(sql: str) -> list[list[str]]:
    out = subprocess.run(["psql", "-tA", "-F", "\t", "-c", sql], check=True, capture_output=True, text=True).stdout
    return [line.split("\t") for line in out.splitlines() if line.strip()]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", default="the migrations in bbc-chatbot-api/migrations, replayed on a clean Postgres 16")
    ap.add_argument("--out", default=str(ROOT.parent / "docs" / "schema" / "DICTIONARY.md"))
    a = ap.parse_args()

    tables = q("""
        select c.relname, c.relrowsecurity
          from pg_class c join pg_namespace n on n.oid = c.relnamespace
         where n.nspname = 'public' and c.relkind in ('r','p')
         order by c.relname""")
    lines = [
        "# Database dictionary (generated)",
        "",
        f"Generated by `bbc-chatbot-api/ci/schema_dictionary.py` from {a.source}.",
        "Do not edit by hand — regenerate. The older hand-written dictionaries in",
        "`docs/DATABASE_DICTIONARY*.md` describe March 2026 and are kept for history.",
        "",
        f"{len(tables)} tables.",
        "",
    ]
    for name, rls in tables:
        lines += [f"## `{name}`", "", f"RLS: {'on' if rls == 't' else '**off**'}", "",
                  "| column | type | null | default |", "|---|---|---|---|"]
        for col, typ, nullable, default in q(f"""
            select column_name, data_type, is_nullable, coalesce(column_default, '')
              from information_schema.columns
             where table_schema = 'public' and table_name = '{name}'
             order by ordinal_position"""):
            d = default.replace("|", "\\|")
            lines.append(f"| `{col}` | {typ} | {'yes' if nullable == 'YES' else 'no'} | {('`' + d + '`') if d else ''} |")
        idx = q(f"select indexname, indexdef from pg_indexes where schemaname = 'public' and tablename = '{name}' order by indexname")
        if idx:
            lines += ["", "Indexes:", ""]
            for iname, idef in idx:
                using = idef.split(" USING ", 1)[-1]
                lines.append(f"- `{iname}` — {using}")
        lines.append("")
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({len(tables)} tables)")


if __name__ == "__main__":
    main()
